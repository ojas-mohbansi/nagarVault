// Shared icon primitives for the officer console.
//
// These are deliberately small, pure, inline-SVGs. The console is air-gapped, so every
// visual mark must be present at build time with zero network dependency — no icon font,
// no sprite sheet loaded from a URL, no runtime-computed glyphs.
//
// Every icon takes an optional `size` shorthand that sets width and height together. That is
// the API the call sites use (`<LogoutIcon size={14} />`); without it, passing `size` to an SVG
// element is not a valid React attribute and fails the type check. Explicit width/height still
// win, since props are spread after the derived attributes.

import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement> & { size?: number };

export function PlayIcon({ size = 16, ...props }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.8}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      <polygon points="5 3 19 12 5 21 5 3" />
    </svg>
  );
}

